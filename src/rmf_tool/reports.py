"""Generated run reports (plan §4.5, §7.1), all under ``runs/<id>/reports/``:

- ``check.json`` and ``check.md``: written by every ``rmf check`` (the selection it ran);
- ``status.md`` and ``metrics.json``: written by every ``rmf status``;
- ``assumptions.md``: ``rmf report assumptions`` (also part of ``rmf build``, HYB-002).

Every report is deterministic (no timestamps), so re-running a command on an unchanged run
rewrites identical bytes. The package manifest lists only the assumptions report: the
others are written by the commands that read the manifest's freshness.
"""

from __future__ import annotations

import json
import statistics
from typing import Any

from rmf_tool import baseline as baseline_mod
from rmf_tool import build, refs
from rmf_tool.check.context import Context
from rmf_tool.check.rules.content import SSP_DIR, family_records
from rmf_tool.findings import Finding, report
from rmf_tool.run import interviews, scope
from rmf_tool.run.assumptions import REPORT_FILE as ASSUMPTIONS_REPORT
from rmf_tool.run.assumptions import load as load_assumptions
from rmf_tool.run.model import JOURNAL_FILE, REPORTS_DIR, Run
from rmf_tool.run.status import Status

CHECK_JSON = f"{REPORTS_DIR}/check.json"
CHECK_MD = f"{REPORTS_DIR}/check.md"
STATUS_MD = f"{REPORTS_DIR}/status.md"
METRICS_JSON = f"{REPORTS_DIR}/metrics.json"
GENERATED = "<!-- generated by `rmf {cmd}`; do not edit (INV-2) -->"

_count = {"type": "integer", "minimum": 0}
_pct = {"type": ["number", "null"], "minimum": 0, "maximum": 100}
METRICS_SCHEMA: dict[str, Any] = {
    "$schema": "https://json-schema.org/draft/2020-12/schema",
    "title": "runs/<run-id>/reports/metrics.json",
    "type": "object",
    "additionalProperties": False,
    "required": ["run_id", "mode", "done", "tasks", "coverage", "ssp_status_mix",
                 "median_statement_words", "answers", "assumptions", "journal"],
    "properties": {
        "run_id": {"type": "string"},
        "mode": {"enum": ["synthetic", "hybrid"]},
        "done": {"type": "boolean"},
        "tasks": {"type": "object", "additionalProperties": False,
                  "required": ["active", "done", "deferred", "lifecycle", "out_of_scope"],
                  "properties": {k: _count for k in ("active", "done", "deferred", "lifecycle",
                                                     "out_of_scope")}},
        "coverage": {"type": "object", "additionalProperties": False,
                     "required": ["baseline", "ssp_statements", "sar_determinations",
                                  "ssp_pct", "sar_pct"],
                     "properties": {"baseline": _count, "ssp_statements": _count,
                                    "sar_determinations": _count, "ssp_pct": _pct,
                                    "sar_pct": _pct}},
        "ssp_status_mix": {"type": "object", "additionalProperties": _count},
        "median_statement_words": {"type": ["number", "null"], "minimum": 0},
        "answers": {"type": "object", "additionalProperties": False,
                    "required": ["total", "simulated", "human", "simulated_pct"],
                    "properties": {"total": _count, "simulated": _count, "human": _count,
                                   "simulated_pct": _pct}},
        "assumptions": _count,
        "journal": {"type": "object", "additionalProperties": False,
                    "required": ["checkpoints", "retries", "corrections"],
                    "properties": {k: _count for k in ("checkpoints", "retries",
                                                       "corrections")}},
    },
}


def write(run: Run, rel: str, text: str) -> bool:
    return build.write_output(run, rel, text)


def _pct(part: int, whole: int) -> float | None:
    return round(100 * part / whole, 1) if whole else None


def _cell(text: Any) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


# --- check ------------------------------------------------------------------------------

def deferred_citations(run: Run) -> int:
    """Framework citations to references still pending acquisition (plan §5.0, p2x)."""
    try:
        index = refs.load_index(run.repo)
    except refs.IndexFileError:
        return 0
    pending = {str(r["id"]) for r in index["references"]
               if r.get("status") == "pending-acquisition"}
    return sum(1 for e in run.framework.entities for c in e.data.get("citations") or []
               if isinstance(c, dict) and c.get("ref") in pending)


def check_report(run: Run, findings: list[Finding], rules_run: list[str]) -> dict[str, Any]:
    """The ``rmf check --format json`` shape (plan §4.5)."""
    data = report(findings, rules_run)
    data["summary"]["degraded"] = Context(run).degraded_refs
    data["summary"]["deferred_citations"] = deferred_citations(run)
    return data


def check_markdown(run: Run, data: dict[str, Any], selection: str) -> str:
    s = data["summary"]
    lines = [f"# Check report — {run.run_id}", "", GENERATED.format(cmd="check"), "",
             f"Selection: {selection}. Errors: {s['errors']}. Warnings: {s['warnings']}. "
             f"Rules run: {len(s['rules_run'])}.", ""]
    if s["degraded"]:
        lines += [f"Degraded references: {', '.join(s['degraded'])} (DEGRADED-001).", ""]
    if not data["findings"]:
        lines.append("No findings.")
    else:
        lines += ["| Severity | Rule | Where | Message |", "|---|---|---|---|"]
        for f in data["findings"]:
            where = (f["path"] or "") + (f":{f['line']}" if f["line"] is not None else "")
            lines.append(f"| {f['severity']} | {f['rule']} | {_cell(where) or '-'} | "
                         f"{_cell(f['message'])} |")
    return "\n".join(lines) + "\n"


def write_check(run: Run, data: dict[str, Any], selection: str) -> None:
    write(run, CHECK_JSON, json.dumps(data, indent=2) + "\n")
    write(run, CHECK_MD, check_markdown(run, data, selection))


# --- status and metrics -----------------------------------------------------------------

def _journal_counts(run: Run) -> dict[str, int]:
    path = run.path(JOURNAL_FILE)
    text = path.read_text(encoding="utf-8") if path.is_file() else ""
    heads = [line for line in text.splitlines() if line.startswith("## ")]
    return {"checkpoints": sum(" · CHECKPOINT · " in h for h in heads),
            "retries": sum(" · RETRY · " in h for h in heads),
            "corrections": sum(" · CORRECTION · " in h for h in heads)}


def metrics(run: Run, st: Status) -> dict[str, Any]:
    states = [t.state for t in st.tasks.values()]
    baseline = set(baseline_mod.control_ids(run))
    statements = [item for _, item in family_records(Context(run), SSP_DIR, "controls")
                  if item.get("control_id") in baseline]
    mix: dict[str, int] = {}
    for item in statements:
        mix[str(item.get("status"))] = mix.get(str(item.get("status")), 0) + 1
    words = [len(str(item.get("statement", "")).split()) for item in statements]
    answers = [a for i in interviews.load_all(run) for a in i.answers]
    simulated = sum(a.fields.get("tag") == "SIMULATED" for a in answers)
    human = sum(a.fields.get("tag") == "HUMAN" for a in answers)
    return {
        "run_id": st.run_id,
        "mode": st.mode,
        "done": st.done,
        "tasks": {"active": states.count(scope.ACTIVE), "done": len(st.done_tasks),
                  "deferred": states.count(scope.DEFERRED),
                  "lifecycle": states.count(scope.LIFECYCLE),
                  "out_of_scope": states.count(scope.OUT_OF_SCOPE)},
        "coverage": {"baseline": st.baseline, "ssp_statements": st.statements,
                     "sar_determinations": st.determinations,
                     "ssp_pct": _pct(st.statements, st.baseline),
                     "sar_pct": _pct(st.determinations, st.baseline)},
        "ssp_status_mix": dict(sorted(mix.items())),
        "median_statement_words": statistics.median(words) if words else None,
        "answers": {"total": len(answers), "simulated": simulated, "human": human,
                    "simulated_pct": _pct(simulated, len(answers))},
        "assumptions": len(load_assumptions(run)[0]),
        "journal": _journal_counts(run),
    }


def status_markdown(run: Run, st: Status, m: dict[str, Any]) -> str:
    t, c = m["tasks"], m["coverage"]
    lines = [f"# Status — {run.run_id}", "", GENERATED.format(cmd="status"), "",
             f"Mode: {run.mode}. Active tasks done: {t['done']}/{t['active']}; deferred "
             f"{t['deferred']}, lifecycle {t['lifecycle']}, out of scope {t['out_of_scope']}.",
             "",
             f"SSP statements: {c['ssp_statements']}/{c['baseline']}. SAR determinations: "
             f"{c['sar_determinations']}/{c['baseline']}.", ""]
    if st.next is None:
        lines.append("Next: none, every active task is done (`rmf check --final`).")
    else:
        fam = f" (family {st.family})" if st.family else ""
        lines.append(f"Next: {st.next} {st.tasks[st.next].name}{fam}.")
    lines += ["", "| Task | Name | State | Done | Missing |", "|---|---|---|---|---|"]
    for s in st.tasks.values():
        detail = "; ".join(s.missing) or (s.rationale if s.state != scope.ACTIVE else "") or ""
        lines.append(f"| {s.id} | {_cell(s.name)} | {s.state} | "
                     f"{'yes' if s.done else 'no'} | {_cell(detail) or '-'} |")
    return "\n".join(lines) + "\n"


def write_status(run: Run, st: Status) -> dict[str, Any]:
    m = metrics(run, st)
    write(run, METRICS_JSON, json.dumps(m, indent=2) + "\n")
    write(run, STATUS_MD, status_markdown(run, st, m))
    return m


# --- assumptions ------------------------------------------------------------------------

def write_assumptions(run: Run) -> bool:
    return write(run, ASSUMPTIONS_REPORT, build.assumptions_report(run))
