def _missing_message(extractor: str) -> str:
    return (
        f"PDF extraction with {extractor!r} needs the optional [extract] extra: "
        "run `EXTRACT=1 scripts/bootstrap.sh` (or `uv sync --extra extract`)."
    )


def _open(extractor: str, pdf_path: Path) -> _Backend:
    if extractor not in EXTRACTORS:
        raise ValueError(f"unknown extractor {extractor!r}; expected one of {EXTRACTORS}")
    if not pdf_path.exists():
        raise FileNotFoundError(pdf_path)
    if extractor == "pymupdf":
        return _PyMuPDF(pdf_path)
    return _PdfPlumber(pdf_path)


def _ocr_textpage(page: Any) -> Any:
    """OCR a page with Tesseract via PyMuPDF (opt-in only; never in tests or CI)."""
    return page.get_textpage_ocr(language="eng", dpi=300, full=True)


class _PyMuPDF:
    def __init__(self, pdf_path: Path) -> None:
        try:
            import pymupdf
        except ImportError as exc:
            raise ExtractorUnavailable(_missing_message("pymupdf")) from exc
        self._m = pymupdf
        self._doc = pymupdf.open(pdf_path)
        self.pages = len(self._doc)
        self._flags = pymupdf.TEXTFLAGS_DICT & ~pymupdf.TEXT_PRESERVE_IMAGES

    def outline(self) -> list[tuple[int, str, int]]:
        return [(int(e[0]), str(e[1]), int(e[2])) for e in self._doc.get_toc(simple=True)]

    def page(
        self, index: int, *, tables: bool, ocr: bool = False, glyphs: GlyphMap | None = None
    ) -> PageData:
        p = self._doc[index]
        textpage = _ocr_textpage(p) if ocr else None
        d: Any = p.get_text("dict", flags=self._flags, textpage=textpage, sort=False)
        data = PageData(
            width=p.rect.width,
            height=p.rect.height,
            label=p.get_label() or "",
            has_images=bool(p.get_images()),
        )
        for b in d["blocks"]:
            if b.get("type") != 0:
                continue
            lines = []
            for ln in b["lines"]:
                spans = [s for s in ln["spans"] if s["text"]]
                if not spans:
                    continue
                inked = [s for s in spans if s["text"].strip()] or spans
                dx, dy = ln["dir"]
                for sp in spans:
                    data.pua += _pua_tokens(sp["font"], sp["text"])
                lines.append(
                    Line(
                        text="".join(_apply_glyphs(sp["text"], sp["font"], glyphs) for sp in spans),
                        spans=tuple((sp["font"], sp["text"]) for sp in spans),
                        x0=ln["bbox"][0],
                        x1=ln["bbox"][2],
                        y=max(s["origin"][1] for s in inked),
                        horizontal=dx > 0.99 and abs(dy) < 0.01,
                        bold=all(s["flags"] & 16 or "bold" in s["font"].lower() for s in inked),
                        size=max(s["size"] for s in inked),
                    )
                )
            if lines:
                data.blocks.append(Block(lines))
        if tables:
            try:
                found: Any = p.find_tables(use_layout=False)
                if found.tables:
                    words: Any = p.get_text("words", flags=self._flags, textpage=textpage)
                    data.tables = [
                        Table(
                            [_cells_text(row.cells, words, glyphs) for row in t.rows],
                            _bbox(t.bbox),
                        )
                        for t in found.tables
                    ]
            except Exception:  # never let a table crash the extraction
                data.tables, data.table_error = [], True
        return data

    def close(self) -> None:
        self._doc.close()


def _bbox(box: Any) -> tuple[float, float, float, float]:
    x0, y0, x1, y1 = (float(v) for v in box)
    return x0, y0, x1, y1


def _cells_text(cells: list[Any], words: list[Any], glyphs: GlyphMap | None) -> list[str]:
    """Cell text from MuPDF words whose centre lies in the cell. Table.extract() glues
    words together on PDFs that position every glyph (e.g. Word output)."""
    out = []
    for cell in cells:
        if cell is None:
            out.append("")
            continue
        x0, y0, x1, y1 = cell
        text = " ".join(
            w[4] for w in words if x0 <= (w[0] + w[2]) / 2 <= x1 and y0 <= (w[1] + w[3]) / 2 <= y1
        )
        # "non- repudiation" -> "non-repudiation"
        out.append(_apply_glyphs(_HYPHEN_BREAK.sub("-", text), "", glyphs))
    return out


class _PdfPlumber:
    """pdfplumber fallback (MIT): no outline headings and simpler block grouping."""

    def __init__(self, pdf_path: Path) -> None:
        try:
            import pdfplumber
        except ImportError as exc:
            raise ExtractorUnavailable(_missing_message("pdfplumber")) from exc
        self._pdf = pdfplumber.open(pdf_path)
        self.pages = len(self._pdf.pages)

    def outline(self) -> list[tuple[int, str, int]]:
        return []

    def page(
        self, index: int, *, tables: bool, ocr: bool = False, glyphs: GlyphMap | None = None
    ) -> PageData:
        p = self._pdf.pages[index]
        data = PageData(width=float(p.width), height=float(p.height), has_images=bool(p.images))
        block: list[Line] = []
        for tl in p.extract_text_lines(strip=True, return_chars=True):
            chars = tl["chars"]
            data.pua += _pua_tokens("", tl["text"])
            ln = Line(
                text=_apply_glyphs(tl["text"], "", glyphs),
                spans=(("", tl["text"]),),
                x0=float(tl["x0"]),
                x1=float(tl["x1"]),
                y=float(tl["bottom"]),
                horizontal=all(c.get("upright", True) for c in chars),
                bold=all("bold" in str(c.get("fontname", "")).lower() for c in chars),
                size=max((float(c.get("size", 0)) for c in chars), default=0.0),
            )
            if block and ln.y - block[-1].y > 1.7 * max(ln.size, 1.0):
                data.blocks.append(Block(block))
                block = []
            block.append(ln)
        if block:
            data.blocks.append(Block(block))
        if tables:
            try:
                data.tables = [
                    Table(
                        [[_apply_glyphs(c or "", "", glyphs) for c in row] for row in t.extract()],
                        _bbox(t.bbox),
                    )
                    for t in p.find_tables()
                ]
            except Exception:  # never let a table crash the extraction
                data.tables, data.table_error = [], True
        p.flush_cache()
        return data

    def close(self) -> None:
        self._pdf.close()
