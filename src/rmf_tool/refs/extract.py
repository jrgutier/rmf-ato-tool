"""Deterministic PDF -> Markdown extraction for the reference library (AC-4a, plan D1).

Output, per reference ID, in `out_dir` (normally `references/text/`):

- `<ID>.md`: an HTML-comment preamble (doc, source sha256, extractor and versions,
  OCR flag, stripped header/footer patterns), then for every physical page a
  `<!-- page N -->` marker (with `label="..."` when the PDF defines page labels),
  followed by the page text. Headings come from the outline and the §6.7 regex set
  (`toc.py`); ruled tables become pipe tables. LF endings, no timestamps.
- `<ID>.toc.yaml`: one entry per heading (`toc.py`), used for citation resolution.

Two passes over the PDF: the first collects margin lines to detect running headers
and footers (`headers.py`) and infers what private-use ligature glyphs stand for
(`infer_glyphs`); the second writes each page as it is read. PyMuPDF
(default, AGPL) and pdfplumber are imported lazily from the optional `[extract]` extra.
"""

from __future__ import annotations

import hashlib
import importlib.metadata
import json
import os
import re
import statistics
from collections import Counter, defaultdict
from collections.abc import Iterator
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Protocol

from rmf_tool.refs import headers, toc

# Bump whenever a change here, in headers.py or in toc.py changes output bytes.
RMF_EXTRACT_VERSION = "1"
EXTRACTORS = ("pymupdf", "pdfplumber")

PAGE_MARKER = re.compile(r'^<!-- page (?P<num>\d+)(?: label="(?P<label>[^"]*)")? -->$')
TABLE_FALLBACK = "<!-- table-fallback -->"
# A list label printed apart from its item text: a bullet glyph, "c.", "(a)", "iv)".
_LABEL = re.compile(
    r"^(?:[•▪◦●■□➢✓*o-]|\(?(?:[a-z]{1,2}|\d{1,2}|[ivx]{1,5})[.)]|\([a-z0-9]{1,3}\))$"
)
# Word/Acrobat PDFs often map ligature glyphs (ti, tt, ft, ...) to private-use code
# points, per font. They are resolved against the document's own vocabulary.
_PUA = re.compile("[\ue000-\uf8ff]")
_PUA_TOKEN = re.compile("[A-Za-z\ue000-\uf8ff]+")
LIGATURES = ("ti", "tt", "tti", "ft", "tf", "fi", "fl", "ff", "ffi", "ffl", "fj", "st", "Th")
# Symbol/Wingdings bullets (font code 0xXX shows up as U+F0XX).
SYMBOL_GLYPHS = {
    "\uf0b7": "•", "\uf0a7": "▪", "\uf06c": "●", "\uf06e": "■", "\uf0a8": "□",
    "\uf0d8": "➢", "\uf0fc": "✓", "\uf076": "❖",
}  # fmt: skip
_HYPHEN_BREAK = re.compile(r"(?<=[A-Za-z])- (?=[a-z])")
_PREAMBLE_HEAD = "rmf-extract: generated by `rmf refs extract`. Do not edit; regenerate."
_PREAMBLE_LISTS = ("stripped", "glyph_map")
_PREAMBLE_FIELD = re.compile(r"^(?P<key>[a-z_0-9]+): ?(?P<value>.*)$")
_DIST = {"pymupdf": "pymupdf", "pdfplumber": "pdfplumber"}


class ExtractorUnavailable(RuntimeError):
    """The optional `[extract]` extra (PyMuPDF / pdfplumber) is not installed."""


@dataclass(frozen=True)
class ExtractResult:
    doc_id: str
    text_path: Path
    toc_path: Path
    pages: int
    sha256: str
    extractor: str
    extractor_version: str
    rmf_extract_version: str
    ocr: bool
    ocr_pages: list[int]


# --- backend-neutral page model -------------------------------------------------


@dataclass
class Line:
    """One text line. Vertical position is the baseline: some PDFs carry font metrics
    that inflate line boxes to several times the line height."""

    text: str  # raw text; normalized later (after hyphenation joins)
    x0: float
    x1: float
    y: float  # baseline
    horizontal: bool = True
    bold: bool = False
    size: float = 0.0
    spans: tuple[tuple[str, str], ...] = ()  # (font, text) before glyph mapping


@dataclass
class Block:
    lines: list[Line]


@dataclass
class Table:
    rows: list[list[str]]
    bbox: tuple[float, float, float, float]


@dataclass
class PageData:
    width: float
    height: float
    label: str = ""
    blocks: list[Block] = field(default_factory=list)
    tables: list[Table] = field(default_factory=list)
    table_error: bool = False
    has_images: bool = False
    pua: list[tuple[str, str]] = field(default_factory=list)  # (font, token) with PUA chars


GlyphMap = dict[tuple[str, str], str]  # (font or "", PUA char) -> replacement


class _Backend(Protocol):
    pages: int

    def outline(self) -> list[tuple[int, str, int]]: ...
    def page(
        self, index: int, *, tables: bool, ocr: bool = False, glyphs: GlyphMap | None = None
    ) -> PageData: ...
    def close(self) -> None: ...


# --- public API -------------------------------------------------------------------


def extractor_version(extractor: str) -> str | None:
    """Installed version of the extractor's distribution, or None if not installed."""
    if extractor not in _DIST:
        raise ValueError(f"unknown extractor {extractor!r}; expected one of {EXTRACTORS}")
    try:
        return importlib.metadata.version(_DIST[extractor])
    except importlib.metadata.PackageNotFoundError:
        return None


def is_current(text_entry: dict | None, source_sha256: str, extractor: str) -> bool:
    """True only if the index text entry was built from this PDF by this extractor
    version and this RMF_EXTRACT_VERSION."""
    if not text_entry:
        return False
    version = extractor_version(extractor)
    return (
        version is not None
        and text_entry.get("source_sha256") == source_sha256
        and text_entry.get("extractor") == extractor
        and text_entry.get("extractor_version") == version
        and text_entry.get("rmf_extract_version") == RMF_EXTRACT_VERSION
    )


def extract(
    doc_id: str,
    pdf_path: Path,
    out_dir: Path,
    *,
    source_sha256: str,
    extractor: str = "pymupdf",
    ocr: bool = False,
) -> ExtractResult:
    """Extract `pdf_path` into `out_dir/<doc_id>.md` and `out_dir/<doc_id>.toc.yaml`."""
    version = extractor_version(extractor)
    if version is None:
        raise ExtractorUnavailable(_missing_message(extractor))
    if ocr and extractor != "pymupdf":
        raise ValueError("ocr=True requires extractor='pymupdf'")
    backend = _open(extractor, Path(pdf_path))
    tmp = out_dir / f".{doc_id}.md.tmp"
    try:
        n = backend.pages
        margins: list[list[Line]] = []
        ocr_pages: list[int] = []
        pua: Counter[tuple[str, str]] = Counter()
        vocab: set[str] = set()
        for i in range(n):
            page = backend.page(i, tables=False)
            margins.append([ln for b in page.blocks for ln in b.lines if _is_margin(ln, page)])
            pua.update(page.pua)
            for block in page.blocks:
                for ln in block.lines:
                    vocab.update(
                        t.lower() for t in _PUA_TOKEN.findall(ln.text) if not _PUA.search(t)
                    )
            if ocr and page.has_images and not any(b.lines for b in page.blocks):
                ocr_pages.append(i + 1)
        glyphs = infer_glyphs(pua, vocab)
        strip = headers.detect([_margin_keys(lines, glyphs) for lines in margins], n)
        outline = _outline_by_page(backend.outline(), n)
        outline_nums = {toc.outline_num(t) for entries in outline.values() for _, t in entries}
        outline_nums.discard("")

        out_dir.mkdir(parents=True, exist_ok=True)
        text_path = out_dir / f"{doc_id}.md"
        toc_path = out_dir / f"{doc_id}.toc.yaml"
        entries: list[toc.TocEntry] = []
        slugger = toc.Slugger()
        digest = hashlib.sha256()
        with tmp.open("w", encoding="utf-8", newline="\n") as fh:

            def write(chunk: str) -> None:
                fh.write(chunk)
                digest.update(chunk.encode("utf-8"))

            write(
                _preamble(
                    doc_id, source_sha256, extractor, version, n, ocr_pages, sorted(strip), glyphs
                )
            )
            for i in range(n):
                page = backend.page(i, tables=True, ocr=(i + 1) in ocr_pages, glyphs=glyphs)
                lines, headings = _render_page(page, strip, outline.get(i + 1, []), outline_nums)
                write(_marker(i + 1, page.label))
                if lines:
                    write("\n" + "\n".join(lines) + "\n")
                for h in headings:
                    entries.append(
                        toc.TocEntry(
                            h.level,
                            h.text,
                            i + 1,
                            slugger(h.text),
                            h.num,
                            "outline" if h.kind == "outline" else "regex",
                        )
                    )
        os.replace(tmp, text_path)
        _write_atomic(toc_path, toc.render_toc(doc_id, entries))
    finally:
        backend.close()
        tmp.unlink(missing_ok=True)  # only left behind by a failed run
    return ExtractResult(
        doc_id=doc_id,
        text_path=text_path,
        toc_path=toc_path,
        pages=n,
        sha256=digest.hexdigest(),
        extractor=extractor,
        extractor_version=version,
        rmf_extract_version=RMF_EXTRACT_VERSION,
        ocr=bool(ocr_pages),
        ocr_pages=ocr_pages,
    )


def check(
    doc_id: str,
    pdf_path: Path,
    out_dir: Path,
    *,
    source_sha256: str,
    extractor: str = "pymupdf",
    text_sha256: str | None = None,
) -> list[str]:
    """Problems with the committed extraction of `doc_id`; empty means current.

    Short-circuits on the recorded tuple: it reads the preamble and page markers but
    neither opens the PDF nor imports an extractor. The extractor version is compared
    only when the extra is installed (it is pinned by uv.lock either way). With
    `text_sha256` (the index's `text.sha256`) it also detects hand edits of the text.
    """
    text_path = out_dir / f"{doc_id}.md"
    toc_path = out_dir / f"{doc_id}.toc.yaml"
    if not Path(pdf_path).exists():
        return [f"{doc_id}: source PDF {pdf_path} is missing"]
    if not text_path.exists():
        return [f"{doc_id}: {text_path} is missing; run rmf refs extract --id {doc_id}"]
    meta = read_preamble(text_path)
    if meta is None:
        return [f"{doc_id}: {text_path} has no rmf-extract preamble"]
    problems: list[str] = []
    if text_sha256 is not None and _sha256_file(text_path) != text_sha256:
        problems.append(f"{doc_id}: {text_path} does not match the recorded text sha256")
    expected = {
        "doc": doc_id,
        "source_sha256": source_sha256,
        "extractor": extractor,
        "rmf_extract_version": RMF_EXTRACT_VERSION,
    }
    version = extractor_version(extractor)
    if version is not None:
        expected["extractor_version"] = version
    for key, want in expected.items():
        if meta.get(key) != want:
            problems.append(f"{doc_id}: stale text: {key} is {meta.get(key)!r}, expected {want!r}")
    try:
        pages = int(meta.get("pages", ""))
    except ValueError:
        return [*problems, f"{doc_id}: preamble pages is not an integer"]
    seen = [int(m.group("num")) for m in _markers(text_path)]
    if seen != list(range(1, pages + 1)):
        problems.append(
            f"{doc_id}: page markers are not 1..{pages} in order ({len(seen)} markers found)"
        )
    if not toc_path.exists():
        problems.append(f"{doc_id}: {toc_path} is missing")
    else:
        try:
            bad = [e for e in toc.load_toc(toc_path) if not 1 <= e.page <= pages]
        except Exception as exc:  # malformed YAML or entry shape
            problems.append(f"{doc_id}: {toc_path} is unreadable: {exc}")
        else:
            if bad:
                problems.append(f"{doc_id}: {toc_path} has {len(bad)} entries outside 1..{pages}")
    return problems


def read_preamble(text_path: Path) -> dict[str, Any] | None:
    """Parse the generated preamble; `stripped` and `glyph_map` become lists of strings."""
    meta: dict[str, Any] = {}
    current: list[str] = []
    with text_path.open(encoding="utf-8") as fh:
        if fh.readline().rstrip("\n") != "<!--" or fh.readline().rstrip("\n") != _PREAMBLE_HEAD:
            return None
        for raw in fh:
            line = raw.rstrip("\n")
            if line == "-->":
                return meta
            if line.startswith("  - "):
                current.append(json.loads(line[4:]))
                continue
            m = _PREAMBLE_FIELD.match(line)
            if m:
                key, value = m.group("key"), m.group("value")
                if key in _PREAMBLE_LISTS:
                    current = meta[key] = []
                else:
                    meta[key] = value
    return None


# --- rendering ----------------------------------------------------------------------


def _preamble(
    doc_id: str,
    source_sha256: str,
    extractor: str,
    version: str,
    pages: int,
    ocr_pages: list[int],
    stripped: list[str],
    glyphs: GlyphMap,
) -> str:
    out = [
        "<!--",
        _PREAMBLE_HEAD,
        f"doc: {doc_id}",
        f"source_sha256: {source_sha256}",
        f"extractor: {extractor}",
        f"extractor_version: {version}",
        f"rmf_extract_version: {RMF_EXTRACT_VERSION}",
        f"pages: {pages}",
        f"ocr: {'true' if ocr_pages else 'false'}",
        f"ocr_pages: [{', '.join(str(p) for p in ocr_pages)}]",
        "stripped:",
    ]
    out += [f"  - {json.dumps(s.replace('-->', '- ->'), ensure_ascii=False)}" for s in stripped]
    out.append("glyph_map:")
    out += [
        "  - " + json.dumps(f"{font or '*'} U+{ord(ch):04X} {lig}", ensure_ascii=False)
        for (font, ch), lig in sorted(glyphs.items())
    ]
    out.append("-->")
    return "\n".join(out) + "\n"


def _marker(num: int, label: str) -> str:
    label = headers.normalize(label).replace('"', "'").replace("--", "-")
    attr = f' label="{label}"' if label and label != str(num) else ""
    return f"\n<!-- page {num}{attr} -->\n"


def _margin_keys(lines: list[Line], glyphs: GlyphMap) -> list[headers.MarginLine]:
    """Key margin lines as pass 2 will see them, i.e. after glyph mapping."""
    out: list[headers.MarginLine] = []
    for ln in lines:
        text = "".join(_apply_glyphs(t, font, glyphs) for font, t in ln.spans) or ln.text
        key = headers.pattern_key(text)
        if key:
            out.append(headers.MarginLine(key, ln.y, ln.horizontal))
    return out


def _is_margin(ln: Line, page: PageData) -> bool:
    if ln.horizontal:
        return headers.in_band(ln.y, page.height)
    return headers.in_side_band(ln.x0, ln.x1, page.width)


@dataclass
class _Item:
    x0: float
    x1: float
    top: float
    nlines: int
    block: list[Line] | None = None
    table: Table | None = None

    @classmethod
    def of_lines(cls, lines: list[Line]) -> _Item:
        return cls(
            min(ln.x0 for ln in lines),
            max(ln.x1 for ln in lines),
            min(ln.y - ln.size for ln in lines),
            len(lines),
            block=lines,
        )


def _render_page(
    page: PageData,
    strip: set[str],
    outline: list[tuple[int, str]],
    outline_nums: set[str],
) -> tuple[list[str], list[toc.Heading]]:
    """Render one page body as Markdown lines and return the headings it contains.

    When the outline numbers sections (`outline_nums`), it is authoritative for them and
    the numbered regex is off: otherwise list items ("2. Intended system usage; and")
    and figures that reproduce a heading ("3.1 PREPARE") would become headings.
    """
    tables = [t for t in page.tables if _is_real_table(t)]
    items: list[_Item] = []
    for block in page.blocks:
        kept = [
            ln
            for ln in block.lines
            if headers.normalize(ln.text)
            and not (_is_margin(ln, page) and headers.pattern_key(ln.text) in strip)
            and not any(_inside(ln, t.bbox) for t in tables)
        ]
        if kept:
            items.append(_Item.of_lines(kept))
    for t in tables:
        items.append(_Item(t.bbox[0], t.bbox[2], t.bbox[1], len(t.rows), table=t))
    items = _merge_continuations(_order(items, page.width))
    for it in items:
        if it.block is not None:
            it.block = _join_lines(it.block)

    body_size = _body_size(items)
    headings: list[toc.Heading] = []
    out: list[str] = []
    if page.table_error:
        out += [TABLE_FALLBACK, ""]

    # Outline titles are matched first, at any line of any block on the page.
    marks = _match_outline(items, outline)

    for idx, it in enumerate(items):
        if it.table is not None:
            out += _pipe_table(it.table) + [""]
            continue
        assert it.block is not None
        para: list[str] = []
        lines = it.block
        j = 0
        while j < len(lines):
            mark = marks.get((idx, j))
            if mark is not None:
                level, title, span = mark
                if para:
                    out += para + [""]
                    para = []
                h = toc.Heading(level, title, toc.outline_num(title), "outline")
                headings.append(h)
                out += ["#" * h.level + " " + h.text, ""]
                j += span
                continue
            text = headers.normalize(lines[j].text)
            if not para:  # chunk start: preceded by a blank line or the page marker
                h = toc.match_heading(text)
                if h is not None and h.kind == "numbered" and outline_nums:
                    h = None
                standalone = j + 1 >= len(lines) or (idx, j + 1) in marks
                emphasized = lines[j].bold or lines[j].size >= body_size + 1.5
                if h is not None and (h.kind not in toc.NEEDS_EMPHASIS or standalone or emphasized):
                    headings.append(h)
                    out += ["#" * h.level + " " + h.text, ""]
                    if h.rest:
                        para.append(_escape(h.rest))
                    j += 1
                    continue
            para.append(_escape(text))
            j += 1
        if para:
            out += para + [""]
    while out and out[-1] == "":
        out.pop()
    return out, headings


def _match_outline(
    items: list[_Item], outline: list[tuple[int, str]]
) -> dict[tuple[int, int], tuple[int, str, int]]:
    """Map (item index, line index) -> (level, title, lines spanned) for outline titles."""
    marks: dict[tuple[int, int], tuple[int, str, int]] = {}
    used: set[tuple[int, int]] = set()
    for level, title in outline:
        want = toc.compact(title)
        found = False
        for idx, it in enumerate(items):
            if it.block is None or found:
                continue
            lines = it.block
            for j in range(len(lines)):
                if (idx, j) in used:
                    continue
                acc = ""
                for k in range(j, min(j + 4, len(lines))):
                    if (idx, k) in used:
                        break
                    acc += toc.compact(headers.normalize(lines[k].text))
                    extra = acc[len(want) :] if acc.startswith(want) else None
                    if extra is not None and (extra == "" or extra.isdigit()):
                        # The heading reads as printed, minus a trailing footnote number.
                        text = " ".join(headers.normalize(ln.text) for ln in lines[j : k + 1])
                        if extra:
                            text = re.sub(r"\s*\d+$", "", text)
                        marks[(idx, j)] = (min(max(level, 1), 6), text, k - j + 1)
                        used.update((idx, x) for x in range(j, k + 1))
                        found = True
                        break
                    if len(acc) >= len(want):
                        break
                if found:
                    break
    return marks


def _outline_by_page(
    raw: list[tuple[int, str, int]], pages: int
) -> dict[int, list[tuple[int, str]]]:
    by_page: dict[int, list[tuple[int, str]]] = {}
    for level, title, page in raw:
        clean = toc.outline_title(title)
        if clean and 1 <= page <= pages:
            by_page.setdefault(page, []).append((level, clean))
    return by_page


def _escape(text: str) -> str:
    if text.startswith("#") or text.startswith("<!--"):
        return "\\" + text
    return text


def _merge_continuations(items: list[_Item]) -> list[_Item]:
    """Fold a text block into the previous one when it continues its last line: it
    starts in lowercase, directly below (MuPDF splits hanging-indent list items)."""
    out: list[_Item] = []
    for it in items:
        prev = out[-1] if out else None
        if prev is not None and prev.block and it.block:
            a, b = prev.block[-1], it.block[0]
            tail, head = headers.normalize(a.text), headers.normalize(b.text)
            if (
                0 < b.y - a.y <= 1.6 * max(a.size, b.size, 1.0)
                and b.x0 >= a.x0 - 2
                and head[:1].islower()
                and not _LABEL.match(head.split(" ", 1)[0])
                and not tail.endswith((".", ":", "!", "?"))
            ):
                out[-1] = _Item.of_lines(prev.block + it.block)
                continue
        out.append(it)
    return out


def _join_lines(lines: list[Line]) -> list[Line]:
    """Join a bare bullet glyph to the line it marks, and words split across lines: a
    soft hyphen is dropped, a hard hyphen kept ("organization-\\nwide" ->
    "organization-wide")."""
    out: list[Line] = []
    pending: Line | None = None
    for ln in lines:
        if pending is None:
            pending = Line(**ln.__dict__)
            continue
        cur = pending.text.rstrip()
        nxt = ln.text.lstrip()
        if _LABEL.match(headers.normalize(cur)) and nxt:
            x0 = min(pending.x0, ln.x0)
            pending = Line(**{**ln.__dict__, "text": f"{headers.normalize(cur)} {nxt}", "x0": x0})
            continue
        soft = cur.endswith("\u00ad")
        hard = re.search(r"[A-Za-z]-$", cur) is not None and nxt[:1].islower()
        if (soft or hard) and nxt:
            word, _, rest = nxt.partition(" ")
            pending.text = (cur[:-1] if soft else cur) + word
            if rest.strip():
                out.append(pending)
                pending = Line(**{**ln.__dict__, "text": rest})
            continue
        out.append(pending)
        pending = Line(**ln.__dict__)
    if pending is not None:
        out.append(pending)
    return out


def _is_real_table(t: Table) -> bool:
    return len(t.rows) >= 2 and max((len(r) for r in t.rows), default=0) >= 2


def _inside(ln: Line, bbox: tuple[float, float, float, float]) -> bool:
    cx, cy = (ln.x0 + ln.x1) / 2, ln.y - 0.3 * ln.size
    return bbox[0] <= cx <= bbox[2] and bbox[1] <= cy <= bbox[3]


def _cell(text: str | None) -> str:
    return headers.normalize(text or "").replace("|", "\\|")


def _pipe_table(t: Table) -> list[str]:
    """Render a table; empty rows and columns (merged-cell artifacts) are dropped."""
    width = max(len(r) for r in t.rows)
    rows = [[_cell(c) for c in r] + [""] * (width - len(r)) for r in t.rows]
    keep = [c for c in range(width) if any(r[c] for r in rows)]
    rows = [[r[c] for c in keep] for r in rows if any(r)]
    width = len(keep)
    if not rows:
        return []
    out = ["| " + " | ".join(rows[0]) + " |", "|" + " --- |" * width]
    out += ["| " + " | ".join(r) + " |" for r in rows[1:]]
    return out


def _body_size(items: list[_Item]) -> float:
    sizes = [ln.size for it in items if it.block for ln in it.block for _ in ln.text]
    return statistics.median(sizes) if sizes else 0.0


def _order(items: list[_Item], width: float) -> list[_Item]:
    """Reading order: rows top to bottom, left to right; two-column regions column by
    column when the page clearly has two text columns."""
    mid, gutter = width / 2, width * 0.02
    left = [it for it in items if it.x1 <= mid + gutter]
    right = [it for it in items if it.x0 >= mid - gutter and it.x1 > mid + gutter]
    if not _two_columns(left, right, width):
        return _rows(items)
    side = {id(it) for it in left} | {id(it) for it in right}
    spans = _rows([it for it in items if id(it) not in side])
    out: list[_Item] = []
    top = float("-inf")
    for sep in [*spans, None]:
        bottom = sep.top if sep is not None else float("inf")
        out += _rows([it for it in left if top <= it.top < bottom])
        out += _rows([it for it in right if top <= it.top < bottom])
        if sep is not None:
            out.append(sep)
            top = sep.top
    return out


def _two_columns(left: list[_Item], right: list[_Item], width: float) -> bool:
    def wide(side: list[_Item]) -> bool:
        return (
            sum(it.nlines for it in side) >= 6
            and statistics.median(it.x1 - it.x0 for it in side) >= 0.25 * width
        )

    return bool(left and right) and wide(left) and wide(right)


def _rows(items: list[_Item], tol: float = 2.0) -> list[_Item]:
    """Sort by top; items whose tops are within `tol` points form a row, sorted by x0."""
    out: list[_Item] = []
    row: list[_Item] = []
    for it in sorted(items, key=lambda it: (it.top, it.x0, it.x1, it.nlines)):
        if row and it.top - row[0].top > tol:
            out += sorted(row, key=lambda it: (it.x0, it.top))
            row = []
        row.append(it)
    out += sorted(row, key=lambda it: (it.x0, it.top))
    return out


def infer_glyphs(pua: Counter[tuple[str, str]], vocab: set[str]) -> GlyphMap:
    """Resolve each (font, private-use char) to the ligature that turns the most of its
    words into words the document also spells out; ("", char) pools every font and is
    used where the font is unknown (table cells, pdfplumber). Ambiguous chars stay."""
    words: defaultdict[tuple[str, str], Counter[str]] = defaultdict(Counter)
    for (font, token), n in pua.items():
        if not re.search("[A-Za-z]", token):  # a lone glyph is a symbol, not a ligature
            continue
        for ch in set(_PUA.findall(token)) - SYMBOL_GLYPHS.keys():
            words[(font, ch)][token] += n
            words[("", ch)][token] += n
    glyphs: GlyphMap = {}
    for key in sorted(words):
        ch = key[1]
        scores = [
            sum(n for tok, n in words[key].items() if tok.replace(ch, lig).lower() in vocab)
            for lig in LIGATURES
        ]
        best = max(range(len(LIGATURES)), key=lambda i: (scores[i], -i))
        runner_up = max(s for i, s in enumerate(scores) if i != best)
        if scores[best] > runner_up:
            glyphs[key] = LIGATURES[best]
    return glyphs


def _apply_glyphs(text: str, font: str, glyphs: GlyphMap | None) -> str:
    if not _PUA.search(text):
        return text
    table = glyphs or {}

    def sub(m: re.Match[str]) -> str:
        ch = m.group(0)
        return table.get((font, ch)) or table.get(("", ch)) or SYMBOL_GLYPHS.get(ch, ch)

    return _PUA.sub(sub, text)


def _pua_tokens(font: str, text: str) -> list[tuple[str, str]]:
    return [(font, t) for t in _PUA_TOKEN.findall(text) if _PUA.search(t)]


def _markers(text_path: Path) -> Iterator[re.Match[str]]:
    with text_path.open(encoding="utf-8") as fh:
        for raw in fh:
            m = PAGE_MARKER.match(raw.rstrip("\n"))
            if m:
                yield m


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _write_atomic(path: Path, text: str) -> None:
    tmp = path.with_name(f".{path.name}.tmp")
    tmp.write_text(text, encoding="utf-8", newline="\n")
    os.replace(tmp, path)


