"""`rmf checks-doc`: ``docs/CHECKS.md``, the rule catalog rendered from
``src/rmf_tool/check/registry.yaml`` (plan §6.5). Deterministic; ``--check`` fails when the
committed file differs from a fresh render (INV-2: never hand-edit it)."""

from __future__ import annotations

from collections.abc import Iterable
from pathlib import Path

from rmf_tool.check import Rule, load_registry

CHECKS_PATH = "docs/CHECKS.md"
SCOPES = (("repo", "Repository scope (`rmf ci`, `rmf validate`)"),
          ("run", "Run scope (`rmf check`)"))


def _cell(text: str | None) -> str:
    return " ".join(str(text or "").split()).replace("|", "\\|")


def _severity(rule: Rule) -> str:
    return f"{rule.severity}: {rule.severity_note}" if rule.severity_note else rule.severity


def _fixture(rule: Rule) -> str:
    return f"`{rule.fixture}`" if rule.fixture else f"exempt: {_cell(rule.exempt_reason)}"


def render(rules: Iterable[Rule] | None = None) -> str:
    rules = list(load_registry() if rules is None else rules)
    counts = {scope: sum(r.scope == scope for r in rules) for scope, _ in SCOPES}
    lines = [
        "# Checks",
        "",
        "<!-- generated by `rmf checks-doc` from src/rmf_tool/check/registry.yaml; do not "
        "edit (INV-2) -->",
        "",
        f"{len(rules)} rules: {counts['repo']} repository-scope, {counts['run']} run-scope. "
        "Severity E fails the command, W warns. `Phase` is the phase from which a rule is "
        "enforced (`rmf ci --profile`); `After` is the task at which a run rule starts to "
        "apply outside `--final` (`-`: always). `Fixture` is the negative fixture or test "
        "that proves the rule fires.",
    ]
    for scope, title in SCOPES:
        lines += ["", f"## {title}", "",
                  "| Rule | Sev | AC | Phase | After | Check | Fix | Fixture |",
                  "|---|---|---|---|---|---|---|---|"]
        for r in rules:
            if r.scope != scope:
                continue
            lines.append(f"| {r.id} | {_cell(_severity(r))} | {', '.join(r.ac)} | {r.phase} | "
                         f"{r.applies_after or '-'} | {_cell(r.summary)} | {_cell(r.hint)} | "
                         f"{_fixture(r)} |")
    return "\n".join(lines) + "\n"


def stale(root: Path) -> bool:
    path = root / CHECKS_PATH
    return not path.is_file() or path.read_text(encoding="utf-8") != render()


def write(root: Path) -> bool:
    path = root / CHECKS_PATH
    text = render()
    if path.is_file() and path.read_text(encoding="utf-8") == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return True
