"""``assumptions.yaml`` and the generated ``reports/assumptions.md`` (HYB-001/002)."""

from __future__ import annotations

from typing import Any

from rmf_tool.run.interviews import Interview
from rmf_tool.run.model import ASSUMPTIONS_FILE, REPORTS_DIR, Run, YamlError

REPORT_FILE = f"{REPORTS_DIR}/assumptions.md"


def load(run: Run) -> tuple[list[dict[str, Any]], list[str]]:
    """(assumptions, problems). A missing file reads as no assumptions plus a problem."""
    path = run.path(ASSUMPTIONS_FILE)
    if not path.is_file():
        return [], ["file not found (rmf run init creates it)"]
    try:
        data = run.data(ASSUMPTIONS_FILE)
    except YamlError as exc:
        return [], [str(exc)]
    problems = run.schema_errors("assumptions", data)
    items = data.get("assumptions") if isinstance(data, dict) else None
    return [a for a in items or [] if isinstance(a, dict)], problems


def _cell(text: Any) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def render(run: Run, assumptions: list[dict[str, Any]], interviews: list[Interview]) -> str:
    humans = {k: v for k, v in (run.config.get("humans") or {}).items() if v}
    lines = [
        f"# Assumptions report — {run.run_id}",
        "",
        "<!-- generated by `rmf build`; do not edit (INV-2) -->",
        "",
        f"Mode: {run.mode}. Human respondents: "
        + (", ".join(f"{p} ({n})" for p, n in sorted(humans.items())) or "none") + ".",
        "",
        f"## Assumptions ({len(assumptions)})",
        "",
    ]
    if assumptions:
        lines += ["| ID | Task | Persona | Statement | Rationale |", "|---|---|---|---|---|"]
        for a in sorted(assumptions, key=lambda a: str(a.get("id"))):
            lines.append(f"| {_cell(a.get('id'))} | {_cell(a.get('task', ''))} | "
                         f"{_cell(a.get('persona', ''))} | {_cell(a.get('statement', ''))} | "
                         f"{_cell(a.get('rationale', ''))} |")
    else:
        lines.append("None recorded.")
    tasks: dict[str, list[int]] = {}
    for interview in interviews:
        counts = tasks.setdefault(str(interview.task), [0, 0, 0])
        counts[0] += 1
        for answer in interview.answers:
            tag = answer.fields.get("tag")
            counts[1] += tag == "SIMULATED"
            counts[2] += tag == "HUMAN"
    total = sum(c[1] + c[2] for c in tasks.values())
    simulated = sum(c[1] for c in tasks.values())
    lines += ["", f"## Interview answers ({total}; SIMULATED {simulated})", ""]
    if tasks:
        lines += ["| Task | Interviews | SIMULATED | HUMAN |", "|---|---|---|---|"]
        position = run.position
        for task in sorted(tasks, key=lambda t: (position.get(t, len(position)), t)):
            n, sim, hum = tasks[task]
            lines.append(f"| {task} | {n} | {sim} | {hum} |")
    else:
        lines.append("None recorded.")
    return "\n".join(lines) + "\n"
