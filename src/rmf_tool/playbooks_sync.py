"""`rmf playbooks sync`: regenerate each authored playbook's header from framework/ YAML.

A playbook is ``playbooks/<step>/<task>.md``:

    <!-- BEGIN rmf:header -->
    ...generated: title, step, phases, dependencies, I/O, facts, RACI, persona cards...
    <!-- END rmf:header -->
    <!-- rmf:body authored -->
    ...authored procedure...

Only files marked ``rmf:body authored`` are synced in this phase; the authored body is never
touched. ``--check`` reports a missing, stale or hand-edited header as FW-PB-002.
"""

from __future__ import annotations

import os
import re
from pathlib import Path
from typing import Any

from rmf_tool.findings import Finding
from rmf_tool.framework.load import load
from rmf_tool.framework.model import FRAMEWORK_DIR, Framework

BEGIN = "<!-- BEGIN rmf:header -->"
END = "<!-- END rmf:header -->"
AUTHORED = "<!-- rmf:body authored -->"
_BLOCK = re.compile(re.escape(BEGIN) + r"\n.*?" + re.escape(END), re.S)
RULE = "FW-PB-002"


def _ids(items: list[str] | None) -> str:
    return ", ".join(items or []) or "—"


def header(fw: Framework, task: dict[str, Any], playbook: str) -> str:
    steps = {e.id: e.data for e in fw.of("steps")}
    artifacts = fw.index("artifacts")
    step = steps.get(task["step"], {})
    phases = [p for p in task.get("phases") or [] if p != task.get("primary_phase")]
    outputs = [
        f"{a} ({'produces' if artifacts[a].data.get('producer') == task['id'] else 'updates'})"
        if a in artifacts else a for a in task.get("outputs") or []]
    raci = task.get("raci") or {}
    cards = []
    for pid in [*(raci.get("R") or []), raci.get("A"), *(raci.get("C") or [])]:
        if pid and pid not in [c[0] for c in cards]:
            card = os.path.relpath(f"personas/{pid}.md", os.path.dirname(playbook))
            cards.append((pid, Path(card).as_posix()))
    lines = [
        BEGIN,
        "<!-- Generated by `rmf playbooks sync` from framework/; edit the YAML, not here. -->",
        f"# {task['id']} · {task['name']}",
        "",
        "| Field | Value |",
        "|---|---|",
        f"| Step | {task['step']} {step.get('name', '')} ({task.get('level', 'system')} level"
        f"{', optional' if task.get('optional') else ''}) |",
        f"| Phases | {task.get('primary_phase', '—')} (primary)"
        + (f", {', '.join(phases)}" if phases else "") + " |",
        f"| Depends on | {_ids(task.get('depends_on'))} |",
        f"| Inputs | {_ids(task.get('inputs'))} |",
        f"| Outputs | {', '.join(outputs) or '—'} |",
        f"| Writes facts | {_ids(task.get('writes_facts'))} |",
        f"| Minimum interviews | {task.get('min_interviews', 0)} |",
        f"| RACI | R: {_ids(raci.get('R'))} · A: {raci.get('A', '—')} · C: {_ids(raci.get('C'))}"
        f" · I: {_ids(raci.get('I'))} |",
        "| Persona cards | " + (", ".join(f"[{pid}]({path})" for pid, path in cards) or "—")
        + " |",
        "",
        f"Purpose: {' '.join(str(task.get('purpose', '')).split())}",
        END,
    ]
    return "\n".join(lines)


def _targets(root: Path) -> tuple[Framework, list[tuple[dict[str, Any], str]]]:
    fw = load(root / FRAMEWORK_DIR, root).framework
    out = []
    for e in fw.of("tasks"):
        playbook = e.data.get("playbook")
        if playbook and (root / playbook).is_file():
            out.append((e.data, playbook))
    return fw, out


def synced(text: str, block: str) -> str | None:
    """The playbook with a fresh header, or None when it is not an authored playbook."""
    if AUTHORED not in text:
        return None
    if _BLOCK.search(text):
        return _BLOCK.sub(lambda m: block, text, count=1)
    return block + "\n" + text


def sync(root: Path) -> list[str]:
    fw, targets = _targets(root)
    changed = []
    for task, playbook in targets:
        path = root / playbook
        text = path.read_text(encoding="utf-8")
        new = synced(text, header(fw, task, playbook))
        if new is not None and new != text:
            path.write_text(new, encoding="utf-8")
            changed.append(playbook)
    return changed


def check(root: Path) -> list[Finding]:
    fw, targets = _targets(root)
    findings = []
    for task, playbook in targets:
        text = (root / playbook).read_text(encoding="utf-8")
        new = synced(text, header(fw, task, playbook))
        if new is not None and new != text:
            why = "header stale or edited by hand" if _BLOCK.search(text) else "header missing"
            findings.append(Finding(RULE, "E", f"{why}; run `rmf playbooks sync`", playbook))
    return findings
