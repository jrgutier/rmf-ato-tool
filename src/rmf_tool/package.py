"""`rmf package`: the eMASS-shaped package manifest ``package/manifest.yaml`` (ART-PKG).

Deterministic. It opens with the security authorization package that DoDI 8510.01 (p. 19)
names (security plan, security assessment report, all POA&Ms, authorization decision
document), then lists every framework artifact with its package class (core = AC-16),
producer, run status, the SHA-256 of each file present and the OSCAL documents it maps to
(plan §6.4), then the OSCAL documents, the reports and any degraded reference (plan §7.6).
PKG-001 checks it; GEN-STALE-001 compares it with a fresh render.
"""

from __future__ import annotations

import hashlib
import io
from pathlib import Path
from typing import Any

from ruamel.yaml import YAML

from rmf_tool.run import authorization as ledger
from rmf_tool.run import facts as facts_mod
from rmf_tool.run import scope
from rmf_tool.run.assumptions import REPORT_FILE
from rmf_tool.run.model import FACTS_FILE, MANIFEST_FILE, OSCAL_DIR, Run, YamlError, read_yaml

HEADER = "# Generated by `rmf package` (ART-PKG); do not edit (INV-2).\n"
# DoDI 8510.01 p. 19: "The security authorization documentation package is made up of"
AUTHORIZATION_PACKAGE = (("security-plan", "ART-SSP"), ("security-assessment-report", "ART-SAR"),
                         ("poams", "ART-POAM"), ("authorization-decision", "ART-AODM"))
# the artifact each OSCAL document stands for (plan §6.4, OSCAL column)
OSCAL_ARTIFACT = {"profile": "ART-BASELINE", "ssp": "ART-SSP", "assessment-plan": "ART-SAP",
                  "assessment-results": "ART-SAR", "poam": "ART-POAM"}
INDEX_FILE = "references/index.yaml"
CC_IMPLEMENTATION = "common-control-implementation"


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _files(run: Run, artifact: str) -> list[dict[str, str]]:
    rels = []
    if run.artifact_md(artifact).is_file():
        rels.append(run.rel(run.artifact_md(artifact)))
    rels += [rel for rel, _ in run.data_files(artifact) if rel != MANIFEST_FILE]
    if any(d["path"].startswith(f"{FACTS_FILE}#") for d in
           run.artifacts[artifact].get("data") or []) and run.path(FACTS_FILE).is_file():
        rels.append(FACTS_FILE)
    return [{"path": rel, "sha256": _sha(run.path(rel))} for rel in rels]


def _oscal_files(run: Run, artifact: str) -> list[str]:
    """The run's OSCAL documents that hold part of an artifact (artifacts.yaml ``oscal``)."""
    models = dict.fromkeys(m.partition("#")[0] for m in run.artifacts[artifact].get("oscal") or [])
    return [rel for rel in (f"{OSCAL_DIR}/{m}.json" for m in models) if run.path(rel).is_file()]


def _degraded(run: Run) -> list[dict[str, str]]:
    try:
        index = read_yaml(run.repo / INDEX_FILE) or {}
    except YamlError:
        return []
    return [{"ref": e["id"], "reason": str((e.get("degraded") or {}).get("reason", ""))}
            for e in index.get("references") or [] if e.get("status") == "degraded"]


def _common_control_records(run: Run, artifacts: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """SP 800-37r2 p. 159: the package for common controls that are not system-based includes a
    record of common control implementation details, a file of the run its ledger record names.
    It is present only when an artifact of the package holds that file (CCPA-001)."""
    owner = {f["path"]: a["artifact_id"] for a in artifacts for f in a["files"]}
    out = []
    for record in ledger.load(run) or []:
        controls = record.get("common_controls")
        if record.get("subject") != "common-controls" or not isinstance(controls, dict) \
                or controls.get("system_based") is not False:
            continue
        path = str(controls.get("implementation_record"))
        out.append({"element": CC_IMPLEMENTATION, "record": record.get("id"), "path": path,
                    "artifact_id": owner.get(path), "status":
                    "present" if path in owner else "missing"})
    return out


def manifest(run: Run) -> dict[str, Any]:
    facts = facts_mod.load(run)
    scopes = scope.task_scopes(run)
    seeded = {s.get("artifact") for s in scope.seeded(run)}
    artifacts = []
    for aid, art in run.artifacts.items():
        if aid == "ART-PKG":
            continue
        files = _files(run, aid)
        producer = art.get("producer")
        in_scope = scopes.get(producer) is not None and scopes[producer].state == scope.ACTIVE
        status = ("seeded" if aid in seeded else "present") if files else (
            "missing" if in_scope else "not-in-scope")
        artifacts.append({"artifact_id": aid, "name": art.get("name", ""),
                          "package": art.get("package"), "producer": producer,
                          "status": status, "files": files, "oscal": _oscal_files(run, aid)})
    by_id = {a["artifact_id"]: a for a in artifacts}
    authorization = [{"element": element, "artifact_id": aid, "status": by_id[aid]["status"],
                      "oscal": by_id[aid]["oscal"]}
                     for element, aid in AUTHORIZATION_PACKAGE if aid in by_id]
    authorization += _common_control_records(run, artifacts)
    oscal = []
    for path in sorted(run.path(OSCAL_DIR).glob("*.json")):
        oscal.append({"path": run.rel(path), "model": path.stem,
                      "artifact_id": OSCAL_ARTIFACT.get(path.stem), "sha256": _sha(path)})
    cat = facts_mod.get(facts, "categorization") or {}
    return {
        "package": {
            "run_id": run.run_id,
            "mode": run.mode,
            "as_of": str(run.config.get("as_of")),
            "framework_version": str(run.config.get("framework_version")),
            "oscal_version": str(run.config.get("oscal_version")),
            "system": {
                "system_id": facts_mod.value(facts, "system_id"),
                "system_name": facts_mod.value(facts, "system_name"),
                "acronym": facts_mod.value(facts, "acronym"),
                "categorization": {k: cat.get(k) for k in ("c", "i", "a")} if cat else None,
                "baseline_id": facts_mod.value(facts, "baseline_id"),
            },
            "authorization_package": authorization,
            "artifacts": artifacts,
            "oscal": oscal,
            "reports": [{"path": REPORT_FILE, "sha256": _sha(run.path(REPORT_FILE))}]
            if run.path(REPORT_FILE).is_file() else [],
            "degraded_references": _degraded(run),
        }
    }


def render(run: Run) -> str:
    yaml = YAML()
    yaml.default_flow_style = False
    yaml.width = 4096
    buf = io.StringIO()
    yaml.dump(manifest(run), buf)
    return HEADER + buf.getvalue()


def write(run: Run) -> bool:
    path = run.path(MANIFEST_FILE)
    text = render(run)
    if path.is_file() and path.read_text(encoding="utf-8") == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return True
