"""Render dryrun-review/STATUS.md from findings/*.md and dispositions.yaml (deterministic).

Run from the repository root: `uv run python dryrun-review/render_status.py`.
"""

from __future__ import annotations

import re
from collections import Counter
from pathlib import Path

from ruamel.yaml import YAML

HERE = Path(__file__).parent
HEAD = re.compile(r"^### (F-\d{2}-\d+): (.+)$", re.M)
FIELD = re.compile(r"^- (Kind|Severity): (\S+)", re.M)
ORDER = {"blocker": 0, "major": 1, "minor": 2, "note": 3}


def findings() -> list[dict[str, str]]:
    out = []
    for path in sorted((HERE / "findings").glob("*.md")):
        text = path.read_text(encoding="utf-8")
        heads = list(HEAD.finditer(text))
        for i, m in enumerate(heads):
            body = text[m.end():heads[i + 1].start() if i + 1 < len(heads) else len(text)]
            fields = dict(FIELD.findall(body))
            out.append({"id": m.group(1), "title": m.group(2).strip(), "file": path.name,
                        "kind": fields.get("Kind", ""), "severity": fields.get("Severity", "")})
    return out


def main() -> None:
    disp = YAML(typ="safe").load((HERE / "dispositions.yaml").read_text(encoding="utf-8")) or {}
    rows = findings()
    unknown = sorted(set(disp) - {r["id"] for r in rows})
    if unknown:
        raise SystemExit(f"dispositions name no finding: {', '.join(unknown)}")
    actionable = [r for r in rows if r["kind"] != "positive"]
    counts = Counter(disp.get(r["id"], {}).get("status", "open") for r in actionable)
    lines = ["# Dry-run findings: status", "",
             "<!-- generated by dryrun-review/render_status.py from findings/*.md and "
             "dispositions.yaml; do not edit -->", "",
             f"{len(rows)} findings, {len(rows) - len(actionable)} of them positive. Of the "
             f"{len(actionable)} others: {counts['fixed']} fixed, {counts['partly']} partly "
             f"fixed, {counts['open']} open.", "",
             "| Finding | Severity | Kind | Status | Title | What changed |",
             "|---|---|---|---|---|---|"]
    for r in sorted(actionable, key=lambda r: (ORDER.get(r["severity"], 9),
                                               disp.get(r["id"], {}).get("status", "open")
                                               != "open", r["id"])):
        d = disp.get(r["id"], {})
        title = r["title"].replace("|", "\\|")
        note = str(d.get("note", "")).replace("|", "\\|")
        lines.append(f"| [{r['id']}](findings/{r['file']}) | {r['severity']} | {r['kind']} | "
                     f"{d.get('status', 'open')} | {title} | {note} |")
    (HERE / "STATUS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"STATUS.md: {dict(counts)}")


if __name__ == "__main__":
    main()
